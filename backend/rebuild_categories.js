function resolveMagnumCategory(fullPath) {
  if (!fullPath || !fullPath.includes(' > ')) return null;
  
  const parts = fullPath.split(' > ').map(p => p.trim()).filter(Boolean);
  if (parts.length < 2) return null;
  
  // Skip non-food categories (fishing, sports, beauty, etc.)
  const topLevel = parts[0];
  if (!['Продукты питания', 'Детские товары'].includes(topLevel)) return null;
  
  // Find unified parent from the 2nd-level Magnum category
  const magnumParent = parts[1]; // e.g. "Молочные продукты, яйца"
  const unifiedParent = MAGNUM_PARENT_MAP[magnumParent];
  if (!unifiedParent) return null;
  
  // Find unified child from the leaf Magnum category
  const leaf = parts[parts.length - 1]; // e.g. "Молоко, сливки"
  const unifiedChild = MAGNUM_CHILD_MAP[leaf];
  if (!unifiedChild) return null;
  
  return [unifiedParent, unifiedChild];
}

function resolveYandexCategory(slug) {
  if (!slug) return null;
  // Try direct mapping
  if (YANDEX_TO_UNIFIED[slug]) return YANDEX_TO_UNIFIED[slug];
  // Some Yandex categories come in Russian (mixed) - try flat map
  if (FLAT_CATEGORY_MAP[slug] !== undefined) return FLAT_CATEGORY_MAP[slug];
  return null;
}

function resolveFlatCategory(name) {
  if (!name) return null;
  if (FLAT_CATEGORY_MAP[name] !== undefined) return FLAT_CATEGORY_MAP[name];
  return null;
}

