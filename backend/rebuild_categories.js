async function main() {
  await mongoose.connect(process.env.MONGO_URI, { dbName: process.env.MONGO_DB_NAME || 'scoutalgo' });
  const Category = require('./src/models/Category');
  const Product = require('./src/models/Product');
  
  console.log('=== CATEGORY HIERARCHY REBUILD ===\n');
  
  // Step 1: Delete all existing categories
  console.log('Step 1: Deleting all existing categories...');
  const deleted = await Category.deleteMany({});
  console.log(`  Deleted ${deleted.deletedCount} categories\n`);
  
  // Step 2: Create parent categories
  console.log('Step 2: Creating parent categories...');
  const parentMap = new Map(); // parentName → parentId
  const childMap = new Map();  // childName → childId
  
  for (const [parentName, config] of Object.entries(CATEGORY_HIERARCHY)) {
    const parent = await Category.create({
      name: parentName,
      icon: config.icon,
      parent: null,
      sort_order: Object.keys(CATEGORY_HIERARCHY).indexOf(parentName)
    });
    parentMap.set(parentName, parent._id);
    console.log(`  ✅ ${config.icon} ${parentName} (${config.children.length} children)`);
    
    // Create children
    for (let i = 0; i < config.children.length; i++) {
      const childName = config.children[i];
      const child = await Category.create({
        name: childName,
        icon: config.icon,
        parent: parent._id,
        sort_order: i
      });
      childMap.set(`${parentName}::${childName}`, child._id);
    }
  }
  
  const totalParents = parentMap.size;
  const totalChildren = childMap.size;
  console.log(`\n  Created ${totalParents} parents, ${totalChildren} children = ${totalParents + totalChildren} total\n`);
  
  // Step 3: Build mapping from raw category names → child category ID
  // We need to process ALL products and update their category references
  console.log('Step 3: Fetching all products to update categories...');
  
  const api = axios.create({
    baseURL: process.env.EXTERNAL_API_BASE,
    headers: { 'Authorization': `Bearer ${process.env.EXTERNAL_API_TOKEN}` },
    timeout: 120000
  });
  
  const files = [
    { id: 'airba_fresh_almaty_mapped', type: 'flat' },
    { id: 'airba_fresh_astana_mapped', type: 'flat' },
    { id: 'arbuz_kz_almaty_mapped', type: 'arbuz' },
    { id: 'arbuz_kz_astana_mapped', type: 'arbuz' },
    { id: 'magnum_almaty_mapped', type: 'magnum' },
    { id: 'magnum_astana_mapped', type: 'magnum' },
    { id: 'wolt_market_almaty_mapped', type: 'flat' },
    { id: 'wolt_market_astana_mapped', type: 'flat' },
    { id: 'yandex_lavka_almaty_mapped', type: 'yandex' },
    { id: 'yandex_lavka_astana_mapped', type: 'yandex' },
  ];
  
  // Build a map: product title → category ID (using API data)
  // We'll match products by their csv_name or normalized_name
  const titleToCategoryId = new Map(); // title (exact) → categoryId
  let mapped = 0, unmapped = 0, skipped = 0;
  
  for (const file of files) {
    try {
      const res = await api.get(`/api/csv-data/${file.id}`);
      const records = res.data.data || res.data || [];
      console.log(`\n  Processing ${file.id} (${records.length} records)...`);
      
      let fileMapped = 0, fileUnmapped = 0, fileSkipped = 0;
      
      for (const record of records) {
        const title = record.title;
        if (!title) continue;
        
        const rawCat = record.category_full_path || record.category || '';
        if (!rawCat) { fileSkipped++; continue; }
        
        let resolved = null;
        
        if (file.type === 'magnum') {
          resolved = resolveMagnumCategory(rawCat);
        } else if (file.type === 'yandex') {
          resolved = resolveYandexCategory(rawCat);
        } else if (file.type === 'flat') {
          resolved = resolveFlatCategory(rawCat);
        } else {
          // arbuz - skip (Publication XXX)
          fileSkipped++;
          continue;
        }
        
        if (resolved === null) {
          // null means "skip this promo category"
          fileSkipped++;
          continue;
        }
        
        if (!resolved) {
          fileUnmapped++;
          continue;
        }
        
        const [parentName, childName] = resolved;
        const key = `${parentName}::${childName}`;
        const categoryId = childMap.get(key);
        
        if (categoryId) {
          titleToCategoryId.set(title, categoryId);
          fileMapped++;
        } else {
          fileUnmapped++;
        }
      }
      
      console.log(`    Mapped: ${fileMapped}, Unmapped: ${fileUnmapped}, Skipped promo: ${fileSkipped}`);
      mapped += fileMapped;
      unmapped += fileUnmapped;
      skipped += fileSkipped;
    } catch (e) {
      console.log(`    ERROR: ${e.message}`);
    }
  }
  
  console.log(`\n  Total: Mapped ${mapped}, Unmapped ${unmapped}, Skipped promo ${skipped}`);
  console.log(`  Unique title→category mappings: ${titleToCategoryId.size}\n`);
  
  // Step 4: Update products in batches
  console.log('Step 4: Updating product categories...');
  
  // First reset all categories
  await Product.updateMany({}, { $set: { category: null } });
  console.log('  Reset all product categories to null');
  
  // Now update by title match
  const batchSize = 1000;
  const titles = [...titleToCategoryId.keys()];
  let updated = 0;
  
  for (let i = 0; i < titles.length; i += batchSize) {
    const batch = titles.slice(i, i + batchSize);
    const ops = batch.map(title => ({
      updateMany: {
        filter: { name: title },
        update: { $set: { category: titleToCategoryId.get(title) } }
      }
    }));
    
    const result = await Product.bulkWrite(ops, { ordered: false });
    updated += result.modifiedCount;
    
    if ((i + batchSize) % 5000 === 0 || i + batchSize >= titles.length) {
      console.log(`  Progress: ${Math.min(i + batchSize, titles.length)}/${titles.length} titles processed, ${updated} products updated`);
    }
  }
  
  console.log(`\n  Updated ${updated} products with new categories`);
  
  // Step 5: Verify
  console.log('\nStep 5: Verification...');
  const totalCats = await Category.countDocuments();
  const parents = await Category.countDocuments({ parent: null });
  const children = await Category.countDocuments({ parent: { $ne: null } });
  const withCat = await Product.countDocuments({ category: { $ne: null } });
  const withoutCat = await Product.countDocuments({ $or: [{ category: null }, { category: { $exists: false } }] });
  
  console.log(`  Categories: ${totalCats} total (${parents} parents, ${children} children)`);
  console.log(`  Products with category: ${withCat}`);
  console.log(`  Products without category: ${withoutCat}`);
  
  // Show tree
  console.log('\n  Category Tree:');
  const parentCats = await Category.find({ parent: null }).sort({ sort_order: 1 }).lean();
  for (const p of parentCats) {
    const childCats = await Category.find({ parent: p._id }).sort({ sort_order: 1 }).lean();
    const productCount = await Product.countDocuments({ category: { $in: [p._id, ...childCats.map(c => c._id)] } });
    console.log(`  ${p.icon} ${p.name} (${productCount} products)`);
    for (const c of childCats) {
      const count = await Product.countDocuments({ category: c._id });
      if (count > 0) {
        console.log(`    └─ ${c.name} (${count})`);
      }
    }
  }
  
  await mongoose.disconnect();
  console.log('\n✅ Done!');
}

main().catch(err => {
  console.error('FATAL:', err);
  process.exit(1);
});
